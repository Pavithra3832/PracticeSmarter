function showStatus(message, isError = false) {
    if (!statusElement) return;

    statusElement.textContent = message;
    statusElement.hidden = false;
    statusElement.classList.toggle("is-error", isError);
}

function showCertificate() {
    if (certificateElement) certificateElement.hidden = false;
    if (actionsElement) actionsElement.hidden = false;
    if (statusElement) statusElement.hidden = true;
}

function hideCertificate() {
    if (certificateElement) certificateElement.hidden = true;
    if (actionsElement) actionsElement.hidden = true;
}

function cleanText(value, fallback = "—") {
    if (value === undefined || value === null) return fallback;

    const text = String(value).trim();
    return text || fallback;
}

// Supports Firestore Timestamp, Date, milliseconds, seconds and date strings.
function toDate(value) {
    if (!value) return null;

    if (typeof value.toDate === "function") {
        const date = value.toDate();
        return Number.isNaN(date.getTime()) ? null : date;
    }

    if (value instanceof Date) {
        return Number.isNaN(value.getTime()) ? null : value;
    }

    if (typeof value === "number") {
        const milliseconds = value < 1e12 ? value * 1000 : value;
        const date = new Date(milliseconds);
        return Number.isNaN(date.getTime()) ? null : date;
    }

    if (typeof value === "string") {
        const date = new Date(value);
        return Number.isNaN(date.getTime()) ? null : date;
    }

    return null;
}

function getResultDate(result) {
    return toDate(
        result.createdAt ??
        result.completedAt ??
        result.completionDate ??
        result.updatedAt
    );
}

function formatDate(date) {
    return new Intl.DateTimeFormat("en-IN", {
        day: "2-digit",
        month: "short",
        year: "numeric"
    }).format(date);
}

// The stored overall field is a percentage: e.g. 80 means 80%.
function getPercentage(result) {
    const value = Number(result.overall);

    if (!Number.isFinite(value) || value < 0 || value > 100) {
        return null;
    }

    return value;
}

function createStableCertificateId(resultId, category, difficulty, date) {
    const storageKey = `practiceSmarterCertificateId_${resultId}`;

    // Preserve IDs already generated by the existing certificate page.
    try {
        const savedId = localStorage.getItem(storageKey);
        if (savedId) return savedId;
    } catch (error) {
        console.warn("Certificate ID storage unavailable:", error);
    }

    // Deterministic fallback: the same result generates the same ID.
    const source = `${resultId}|${category}|${difficulty}|${date.getFullYear()}`;
    let hash = 2166136261;

    for (let i = 0; i < source.length; i++) {
        hash ^= source.charCodeAt(i);
        hash = Math.imul(hash, 16777619);
    }

    const shortCode = (hash >>> 0)
        .toString(36)
        .toUpperCase()
        .padStart(7, "0")
        .slice(-7);

    const cleanCategory = category
        .replace(/[^a-zA-Z0-9]/g, "")
        .toUpperCase()
        .slice(0, 12) || "INTERVIEW";

    const cleanDifficulty = difficulty
        .replace(/[^a-zA-Z0-9]/g, "")
        .toUpperCase()
        .slice(0, 12) || "GENERAL";

    const id = `PS-${cleanCategory}-${cleanDifficulty}-${date.getFullYear()}-${shortCode}`;

    try {
        localStorage.setItem(storageKey, id);
    } catch (error) {
        console.warn("Could not save certificate ID:", error);
    }

    return id;
}

async function loadStudentName(user) {
    let displayName = "";

    // Preserve the existing saved local profile fallback.
    try {
        const savedProfile = JSON.parse(
            localStorage.getItem("userProfile") || "null"
        );

        if (savedProfile?.name?.trim()) {
            displayName = savedProfile.name.trim();
        }
    } catch (error) {
        console.warn("Local profile read failed:", error);
    }

    // Prefer the latest Firestore profile when available.
    try {
        const userSnapshot = await getDoc(doc(db, "users", user.uid));

        if (userSnapshot.exists()) {
            const profile = userSnapshot.data();

            if (typeof profile.name === "string" && profile.name.trim()) {
                displayName = profile.name.trim();
            }
        }
    } catch (error) {
        // A missing read permission should not discard an available local name.
        console.warn("Firestore profile name unavailable:", error);
    }

    if (!displayName && user.displayName?.trim()) {
        displayName = user.displayName.trim();
    }

    if (!displayName && user.email) {
        displayName = user.email.split("@")[0];
    }

    return displayName || "PracticeSmarter User";
}

async function loadLatestResult(user) {
    const resultsQuery = query(
        collection(db, "interviewResults"),
        where("userId", "==", user.uid)
    );

    const snapshot = await getDocs(resultsQuery);

    if (snapshot.empty) {
        throw new Error(
            "No interview results were found for your account. Complete an interview practice session first."
        );
    }

    const results = snapshot.docs.map((document) => ({
        id: document.id,
        ...document.data()
    }));

    results.sort((a, b) => {
        const dateA = getResultDate(a)?.getTime() ?? 0;
        const dateB = getResultDate(b)?.getTime() ?? 0;
        return dateB - dateA;
    });

    const result = results[0];
    const percentage = getPercentage(result);

    if (percentage === null) {
        throw new Error(
            "The latest interview result has an invalid overall percentage. Please check the saved interview result."
        );
    }

    const category = cleanText(result.category, "Interview");
    const difficulty = cleanText(result.difficulty, "General");
    const completionDate = getResultDate(result);

    if (!completionDate) {
        throw new Error(
            "The completion date is missing from the latest interview result. Please check its saved date field."
        );
    }

    const studentName = await loadStudentName(user);
    const certificateId = createStableCertificateId(
        result.id,
        category,
        difficulty,
        completionDate
    );

    // Use textContent to avoid treating database content as HTML.
    studentNameElement.textContent = studentName;
    categoryElement.textContent = category;
    difficultyElement.textContent = difficulty;
    scoreElement.textContent = `${(percentage / 10).toFixed(1)}/10`;
    percentageElement.textContent = `${Math.round(percentage)}%`;
    completionDateElement.textContent = formatDate(completionDate);
    certificateIdElement.textContent = certificateId;

    showCertificate();
}

onAuthStateChanged(auth, async (user) => {
    if (!user) {
        window.location.replace("login.html");
        return;
    }

    hideCertificate();
    showStatus("Loading your certificate...");

    try {
        await loadLatestResult(user);
    } catch (error) {
        console.error("Certificate loading failed:", error);

        showStatus(
            error?.message ||
            "Unable to load your certificate. Please try again later.",
            true
        );
    }
});

